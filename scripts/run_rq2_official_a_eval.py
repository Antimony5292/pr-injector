"""Run official A-group evaluation for completed RQ2 Claude patches.

This script evaluates only A/original benchmark tasks. It keeps the RQ2 pairing
table as the source of truth and consumes inputs generated by
build_rq2_official_a_eval_inputs.py.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
INPUT_DIR = ROOT / "experiments" / "rq2_100" / "official_a_eval_inputs"
SWE_PYTHON = ROOT / ".venvs" / "swebench-official" / "bin" / "python"
PRO_ROOT = ROOT / ".external" / "SWE-bench_Pro-os"
DEFAULT_PRO_OUTPUT_DIR = ROOT / "experiments" / "rq2_100" / "official_a_eval_pro_opus46_20260605"


def run(cmd: list[str], cwd: Path) -> None:
    print(" ".join(cmd), flush=True)
    completed = subprocess.run(cmd, cwd=str(cwd), check=False)
    if completed.returncode != 0:
        raise SystemExit(completed.returncode)


def read_instance_ids(path: Path) -> list[str]:
    if not path.exists():
        return []
    return [line.strip() for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--which", choices=["swebench", "verified", "pro", "both", "all"], default="both")
    parser.add_argument("--pairing", default=str(ROOT / "experiments" / "rq2_100" / "rq2_b_p2f_100_final" / "rq2_pairing_table.jsonl"))
    parser.add_argument("--input-dir", default=str(INPUT_DIR))
    parser.add_argument("--results-dir", default=str(ROOT / "experiments" / "rq2_100" / "claude_bedrock_sonnet46_A100_agentonly_strict"))
    parser.add_argument("--model-name", default="claude-bedrock-sonnet-4.6")
    parser.add_argument("--include-invalid-as-empty", action="store_true")
    parser.add_argument("--run-id-prefix", default="rq2_a_official")
    parser.add_argument("--swebench-workers", type=int, default=1)
    parser.add_argument("--verified-workers", type=int, default=1)
    parser.add_argument("--pro-workers", type=int, default=1)
    parser.add_argument("--timeout", type=int, default=1800)
    parser.add_argument("--namespace", default="none")
    parser.add_argument("--dockerhub-username", default="jefzda")
    parser.add_argument("--pro-output-dir", default=str(DEFAULT_PRO_OUTPUT_DIR))
    parser.add_argument("--redo-pro", action="store_true")
    args = parser.parse_args()

    input_dir = Path(args.input_dir).resolve()
    run([
        sys.executable,
        str(ROOT / "scripts" / "build_rq2_official_a_eval_inputs.py"),
        "--pairing",
        args.pairing,
        "--results-dir",
        args.results_dir,
        "--output-dir",
        str(input_dir),
        "--model-name",
        args.model_name,
        *(["--include-invalid-as-empty"] if args.include_invalid_as_empty else []),
    ], ROOT)

    summary = json.loads((input_dir / "summary.json").read_text(encoding="utf-8"))
    print(json.dumps(summary, ensure_ascii=False, indent=2), flush=True)

    if args.which in {"swebench", "all"}:
        ids = read_instance_ids(input_dir / "swebench_instance_ids.txt")
        if ids:
            run([
                str(SWE_PYTHON),
                "-m",
                "swebench.harness.run_evaluation",
                "--dataset_name",
                "princeton-nlp/SWE-bench",
                "--predictions_path",
                str(input_dir / "swebench_predictions.jsonl"),
                "--max_workers",
                str(args.swebench_workers),
                "--instance_ids",
                *ids,
                "--run_id",
                f"{args.run_id_prefix}_swebench",
                "--namespace",
                args.namespace,
                "--timeout",
                str(args.timeout),
            ], ROOT)
        else:
            print("No SWE-bench A predictions to evaluate.", flush=True)

    if args.which in {"verified", "both", "all"}:
        ids = read_instance_ids(input_dir / "verified_instance_ids.txt")
        if ids:
            run([
                str(SWE_PYTHON),
                "-m",
                "swebench.harness.run_evaluation",
                "--dataset_name",
                "princeton-nlp/SWE-bench_Verified",
                "--predictions_path",
                str(input_dir / "verified_predictions.jsonl"),
                "--max_workers",
                str(args.verified_workers),
                "--instance_ids",
                *ids,
                "--run_id",
                f"{args.run_id_prefix}_verified",
                "--namespace",
                args.namespace,
                "--timeout",
                str(args.timeout),
            ], ROOT)
        else:
            print("No verified A predictions to evaluate.", flush=True)

    if args.which in {"pro", "both", "all"}:
        patches = json.loads((input_dir / "pro_patches.json").read_text(encoding="utf-8"))
        if patches:
            cmd = [
                str(SWE_PYTHON),
                "swe_bench_pro_eval.py",
                "--raw_sample_path",
                str(input_dir / "pro_raw_samples.jsonl"),
                "--patch_path",
                str(input_dir / "pro_patches.json"),
                "--output_dir",
                str(Path(args.pro_output_dir).resolve()),
                "--scripts_dir",
                "run_scripts",
                "--num_workers",
                str(args.pro_workers),
                "--dockerhub_username",
                args.dockerhub_username,
                "--use_local_docker",
            ]
            if args.redo_pro:
                cmd.append("--redo")
            run(cmd, PRO_ROOT)
        else:
            print("No Pro A predictions to evaluate.", flush=True)


if __name__ == "__main__":
    main()
